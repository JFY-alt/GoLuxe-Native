/**
 * Sensei lesson data for the Study Room.
 * Each topic is an interactive tutorial taught by Iwao, in the same style
 * as Ishi's How to Play: a board, a coach card, and tap-to-play beats.
 *
 * Board format: 9 strings of 9 chars. X = black, O = white, . = empty.
 * Text markup: **bold** renders amber, *italic* renders italic.
 * Interactive taps default to Black; practice beats may specify White.
 */

export type SenseiMood = 'happy' | 'excited' | 'sad' | 'proud';

export interface SenseiChoice {
  x: number;
  y: number;
  correct: boolean;
  nudge?: string;
}

export interface SenseiBeat {
  /** Independent problems hide targets and retain the solved position for explanation. */
  unmarked?: boolean;
  studentColor?: 'black' | 'white';
  feedback?: string;
  title: string;
  mood: SenseiMood;
  text: string;
  board?: string[];
  /** Sequential tap targets; each correct tap plays the stone. */
  taps?: { x: number; y: number }[];
  /** If true, taps are White's demo moves: no stone placed, just advances. */
  demoWhite?: boolean;
  /** Quiz: several glowing points, only the correct one advances. */
  choices?: SenseiChoice[];
  /** Wrong-tap message. */
  nudge?: string;
  /** Next-button label. Default "Next". Omitted for tap/choice-only beats. */
  button?: string | null;
  chips?: { label: string; value: string | number }[];
  /** Imaginary/ghost markers: translucent dots showing potential (territory, influence). Not stones. */
  marks?: { x: number; y: number; c?: 'black' | 'white' }[];
  /** Highlight full board lines (rows/cols), e.g. when explaining the 3rd/4th line. */
  lines?: { axis: 'row' | 'col'; index: number }[];
}

export interface SenseiLesson {
  id: string;
  title: string;
  beats: SenseiBeat[];
  /** Board size for this lesson. Default 9. */
  boardSize?: 9 | 13 | 19;
}

export const parseSenseiBoard = (rows: string[]): { p: { x: number; y: number }; c: 'black' | 'white' }[] => {
  const stones: { p: { x: number; y: number }; c: 'black' | 'white' }[] = [];
  rows.forEach((row, y) => {
    row.split('').forEach((ch, x) => {
      if (ch === 'X') stones.push({ p: { x, y }, c: 'black' });
      else if (ch === 'O') stones.push({ p: { x, y }, c: 'white' });
    });
  });
  return stones;
};

